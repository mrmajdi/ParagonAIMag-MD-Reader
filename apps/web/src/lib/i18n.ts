const RTL_LOCALES: Locale[] = ['fa', 'ar'];

export function isRtlLocale(locale: Locale): boolean {
  return RTL_LOCALES.includes(locale);
}

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en';
  const candidates = [navigator.language, ...(navigator.languages ?? [])];
  for (const candidate of candidates) {
    const base = candidate.toLowerCase().split('-')[0] as Locale;
    if (base in dictionaries) return base;
  }
  return 'en';
}

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[locale]?.[key] ?? dictionaries.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;
